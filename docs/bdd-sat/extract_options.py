#!/usr/bin/env python3
"""Extract the options of the plugins documented in bdd-sat.tex from the C++ sources and
write them as LaTeX tables (options-<plugin>.tex). Run from this directory:
    python3 extract_options.py
so the tables always match the code."""
import os, re

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "search")
# plugin name -> (source file, function that parses it, or None for the whole file)
PLUGINS = {
    "bdd_sat": ("sat/bdd_encoding.cc", "_parse_bdd_sat_factory"),
    "label_order_goal_chains": ("task_utils/label_order_goal_chains.cc", "_parse_goal_chains"),
    "label_order_relaxed": ("task_utils/label_order_finder.cc", "_parse_relaxed"),
    "label_order_file": ("task_utils/label_order_finder.cc", "_parse_file"),
    "label_order_random": ("task_utils/label_order_finder.cc", "_parse_random"),
    "label_order_tsort": ("task_utils/label_order_finder.cc", "_parse_tsort"),
    "label_order_causal": ("task_utils/label_order_finder.cc", "_parse_causal"),
    "sat": ("search_engines/plugin_sat.cc", None),
    "rintanen": ("search_engines/plugin_rintanen.cc", None),
    "by_iteration": ("sat/length_strategy.cc", "_parse_by_iteration"),
    "by_increment": ("sat/length_strategy.cc", "_parse_by_increment"),
    "one_by_one": ("sat/length_strategy.cc", "_parse_one_by_one"),
    "length_list": ("sat/length_strategy.cc", "_parse_length_list"),
}


def strings(s):
    """Concatenate the C++ string literals in s."""
    return "".join(m.group(1).encode().decode("unicode_escape")
                   for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', s))


def split_args(s):
    """Split a call's argument string at top-level commas."""
    args, depth, cur, inq = [], 0, "", False
    i = 0
    while i < len(s):
        c = s[i]
        if inq:
            cur += c
            if c == "\\": cur += s[i + 1]; i += 1
            elif c == '"': inq = False
        elif c == '"': inq = True; cur += c
        elif c in "([{<": depth += 1; cur += c
        elif c in ")]}>": depth -= 1; cur += c
        elif c == "," and depth == 0: args.append(cur.strip()); cur = ""
        else: cur += c
        i += 1
    if cur.strip(): args.append(cur.strip())
    return args


def body_of(text, func):
    if func is None: return text
    i = text.find(func + "(")
    while i >= 0 and "{" not in text[i:text.find(")", i) + 3]:
        i = text.find(func + "(", i + 1)
    j = text.find("{", i); depth = 0
    for k in range(j, len(text)):
        depth += text[k] == "{"; depth -= text[k] == "}"
        if depth == 0: return text[j:k]
    return text[j:]


def options(path, func):
    text = open(os.path.join(SRC, path)).read()
    body = body_of(text, func)
    vectors = {m.group(1): re.findall(r'"([^"]*)"', m.group(2))
               for m in re.finditer(r'vector<string>\s+(\w+)\s*\{([^}]*)\}', text)}
    out = []
    for m in re.finditer(r'add_(option<(.+?)>|enum_option|list_option<(.+?)>)\s*\(', body):
        depth, k = 1, m.end()
        while depth and k < len(body):
            if body[k] == '"':
                k += 1
                while body[k] != '"': k += 2 if body[k] == "\\" else 1
            depth += body[k] == "("; depth -= body[k] == ")"; k += 1
        args = split_args(body[m.end():k - 1])
        name = strings(args[0])
        if m.group(1) == "enum_option":
            choices = vectors.get(args[1].strip(), [])
            typ = "enum: " + ", ".join(choices)
            doc, default = strings(args[2]), strings(args[3]) if len(args) > 3 else ""
        else:
            typ = (m.group(2) or "list<" + (m.group(3) or "") + ">").replace("std::", "")
            doc = strings(args[1]) if len(args) > 1 else ""
            default = strings(args[2]) if len(args) > 2 and '"' in args[2] else ""
        out.append((name, typ, default, doc))
    return out


def tex(s):
    out = []
    for ch in s:
        out.append({"\\": r"\textbackslash{}", "_": r"\_", "&": r"\&", "%": r"\%", "#": r"\#",
                    "$": r"\$", "{": r"\{", "}": r"\}", "^": r"\^{}", "~": r"\~{}",
                    "<": r"\textless{}", ">": r"\textgreater{}"}.get(ch, ch))
    return "".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    total = 0
    for plugin, (path, func) in PLUGINS.items():
        opts = options(path, func)
        total += len(opts)
        with open(os.path.join(here, f"options-{plugin}.tex"), "w") as f:
            f.write(f"% generated by extract_options.py from src/search/{path} -- do not edit\n")
            f.write("\\begin{longtable}{@{}p{0.27\\linewidth}p{0.13\\linewidth}p{0.54\\linewidth}@{}}\n")
            f.write("\\toprule\noption & default & meaning \\\\\n\\midrule\n\\endhead\n")
            for name, typ, default, doc in opts:
                d = tex(doc)
                if typ.startswith("enum: "): d += " \\emph{(" + tex(typ[6:]) + ")}"
                f.write(f"\\texttt{{{tex(name)}}} & \\texttt{{{tex(default)}}} & {d} \\\\\n")
            f.write("\\bottomrule\n\\end{longtable}\n")
        print(f"{plugin}: {len(opts)} options")
    print("total", total)


if __name__ == "__main__":
    main()
