import re

from lab.parser import Parser


def add_sat_vars_and_clauses(content, props):
    if props["coverage"]:
        regex = re.compile(r"clauses ([0-9]+) vars ([0-9]+) labels ([0-9]+) ")
        match = regex.search(content)
        if match:
             try:
                 clauses = match.group(1)
                 var = match.group(2)
                 #print(f"Found {clauses} {var}")
                 #print(props)
             except IndexError:
                 tools.add_unexplained_error(
                     props,
                     f"Attribute {self.attribute} not found for pattern {self} in "
                     f"file {filename}.",
                 )
             else:
                 props["sat_variables"] = int(var) 
                 props["sat_clauses"] = int(clauses) 
        else:
            all_generated_formulas = re.findall(r"Formula has ([0-9]+) clauses and ([0-9]+) variables.",content)
            if len(all_generated_formulas) != 0:
                (clauses,var) = all_generated_formulas[len(all_generated_formulas)-1]
                props["sat_variables"] = int(var) 
                props["sat_clauses"] = int(clauses) 
            


def add_number_labels(content, props):
    # only try to find number of labels if not generated by SAT output
    if props["coverage"] and "number_labels" not in props:
        ##print(content)
        regex = re.compile(r"reconstruction of plan with ([0-9]+) ")
        match = regex.search(content)
        if match:
             try:
                 value = match.group(1)
                 #print(f"Found {value}")
                 #print(props)
             except IndexError:
                 tools.add_unexplained_error(
                     props,
                     f"Attribute {self.attribute} not found for pattern {self} in "
                     f"file {filename}.",
                 )
             else:
                 value = int(value)
                 props["number_labels"] = value 


class FTSParser(Parser):
    def __init__(self):
        Parser.__init__(self)
        self.add_pattern("number_labels", r"Total labels: (.+)", type=int)
        self.add_pattern("time_steps_with_label", r"Total timesteps with label: (.+)", type=int)
